# 定义两个相同长度的列表
list1 = [-0.03584312,  0.6307912,  -1.4495131,   0.04133042,  0.7432153,  -1.2860187,
  -0.04333423,  0.9148848,  -1.4448581,   0.06747473, 0.8515197,  -1.5170943 ]
list2 = [0.08341989,  0.14708692, 0.372761,   -0.11697252, -0.19862634,  0.22973073,
   0.09144446, -0.25341803,  0.06689692, -0.09542388,  0.08184278,  0.3204137]

import numpy as np


# 2. 转换为 NumPy 数组
# 指定 dtype=np.float64 可以确保使用双精度浮点数进行计算，这是科学计算的标准精度
arr1 = np.array(list1, dtype=np.float64)
arr2 = np.array(list2, dtype=np.float64)

# 3. 对应相加
# NumPy 会直接对两个数组进行向量化加法，速度极快
result_arr = arr1 + arr2

# 4. 打印结果
print("计算结果数组:", result_arr)

# 如果你需要变回普通的 Python 列表
result_list = result_arr.tolist()
print("转回列表:", result_list)